# ---------------------------------------------------------------------------
# Apple ADT encoder (same contract as UniXNU-sheng's make-sheng-adt.py)
# ---------------------------------------------------------------------------
def node(name: str, properties=(), children=()) -> bytes:
    """Serialise one node: property/child counts, 32-byte names, padded values."""
    encoded_name = name.encode()
    if len(encoded_name) > 31:
        raise ValueError(f'ADT node name too long: {name}')
    properties = [('name', encoded_name + b'\0'), *properties]
    result = struct.pack('<II', len(properties), len(children))
    for key, data in properties:
        raw_key = key.encode()
        if len(raw_key) > 31:
            raise ValueError(f'ADT property name exceeds 31 bytes: {key}')
        if not isinstance(data, (bytes, bytearray)):
            raise TypeError(f'{key}: property value must be bytes, not {type(data).__name__}')
        result += struct.pack('<32sI', raw_key, len(data)) + data + bytes(-len(data) % 4)
    return result + b''.join(children)


def _chrp_header(name: bytes, size: int) -> bytearray:
    raw = bytearray(struct.pack('<BBH12s', 0x70, 0, size // 16, name))
    checksum = sum(raw)
    while checksum > 255:
        checksum = (checksum & 255) + (checksum >> 8)
    raw[1] = checksum
    return raw


def empty_nvram_proxy():
    """A fresh volatile CHRP bank for IODTNVRAM with no persistent controller.

    Same 8192-byte layout as the proven QEMU/ArmDTPlatform fixture and
    UniXNU-sheng: `nvram` header, `common` header + 2 KiB data area with an
    Adler-32 checksum at offset 16, then a `free` header.
    """
    image = bytearray(8192)
    image[:16] = _chrp_header(b'nvram', 32)
    image[32:48] = _chrp_header(b'common', 16 + 2048)
    free_at = 32 + 16 + 2048
    image[free_at:free_at + 16] = _chrp_header(b'free', len(image) - free_at)
    struct.pack_into('<I', image, 16, zlib.adler32(image[20:]))
    return [('nvram-bank-size', struct.pack('<I', len(image))),
            ('nvram-bank-count', struct.pack('<I', 1)),
            ('nvram-current-bank', struct.pack('<I', 0)),
            ('nvram-proxy-data', bytes(image))]


def root_matching(uuid: str) -> bytes:
    """`root-matching` plist dictionary selecting the root IOMedia by UUID."""
    text = ('<dict><key>IOProviderClass</key><string>IOMedia</string>'
            '<key>IOPropertyMatch</key><dict><key>UUID</key><string>'
            + uuid.upper() + '</string></dict></dict>\0')
    return text.encode()


def cpu_nodes(cpu_regs: list[int], timebase: int = TIMEBASE) -> list[bytes]:
    nodes = []
    for index, reg in enumerate(cpu_regs):
        nodes.append(node(f'cpu{index}', [
            ('state', b'running\0' if index == 0 else b'waiting\0'),
            ('reg', struct.pack('<I', reg)),
            ('device_type', b'cpu\0'),
            ('compatible', CPU_COMPATIBLE),
            ('timebase-frequency', struct.pack('<I', timebase)),
        ]))
    return nodes


