def parse_adt(data: bytes):
    """Parse Apple ADT bytes into (node tree, consumed bytes). Raises ValueError.

    Paths are the tree paths the platform expert uses: the root node is '/',
    its children are '/chosen', '/cpus', ... (the root's own name property is
    'device-tree' but it is not part of child paths).
    """
    def parse(at: int, parent_path: str):
        if at + 8 > len(data):
            raise ValueError(f'{parent_path or "/"}: truncated node header at {at:#x}')
        prop_count, child_count = struct.unpack_from('<II', data, at)
        at += 8
        if prop_count > 4096 or child_count > 4096:
            raise ValueError(f'{parent_path or "/"}: implausible counts {prop_count}/{child_count}')
        props = {}
        for _ in range(prop_count):
            if at + 36 > len(data):
                raise ValueError(f'{parent_path or "/"}: truncated property header at {at:#x}')
            raw_name, size = struct.unpack_from('<32sI', data, at)
            at += 36
            name, _, _ = raw_name.partition(b'\0')
            if not name or len(name) > 31:
                raise ValueError(f'{parent_path or "/"}: invalid property name {raw_name!r}')
            try:
                name = name.decode('ascii')
            except UnicodeDecodeError:
                raise ValueError(f'{parent_path or "/"}: non-ASCII property name {raw_name!r}') from None
            if name in props:
                raise ValueError(f'{parent_path or "/"}: duplicate property {name}')
            if at + size > len(data):
                raise ValueError(f'{parent_path or "/"}/{name}: value runs past end of file')
            props[name] = data[at:at + size]
            at += (size + 3) & ~3
        if 'name' not in props:
            raise ValueError(f'{parent_path or "/"}: node has no name property')
        own_name = props['name'].rstrip(b'\0').decode('ascii', 'replace')
        node_path = '/' if not parent_path else parent_path.rstrip('/') + '/' + own_name
        children = []
        for _ in range(child_count):
            child, at = parse(at, node_path)
            children.append(child)
        return {'path': node_path, 'props': props, 'children': children}, at

    tree, consumed = parse(0, '')
    return tree, consumed


def walk(tree):
    yield tree
    for child in tree['children']:
        yield from walk(child)


def check_tree(data: bytes, expect: dict, strict_addresses: bool = False) -> list[str]:
    """Validate the emitted/candidate ADT; returns a list of errors (empty = pass)."""
    errors = []
    try:
        tree, consumed = parse_adt(data)
    except ValueError as error:
        return [f'parse failed: {error}']
    if consumed != len(data):
        errors.append(f'{consumed} of {len(data)} bytes consumed (trailing data)')
    root = tree['props']
    if root.get('name') != b'device-tree\0':
        errors.append(f"root node name is {root.get('name')!r}, expected b'device-tree\\0'")
    for required in ('compatible', 'model', 'target-type'):
        if required not in root:
            errors.append(f'root is missing {required}')
    if root.get('model') != b'iPhone10,3\0':
        errors.append(f"root model is {root.get('model')!r}, expected b'iPhone10,3\\0'")
    if root.get('target-type') != b'D22\0':
        errors.append(f"root target-type is {root.get('target-type')!r}, expected b'D22\\0'")

    by_path = {entry['path']: entry for entry in walk(tree)}
    top_names = [child['props'].get('name', b'').rstrip(b'\0').decode() for child in tree['children']]
    for required in REQUIRED_TOP:
        if required not in top_names:
            errors.append(f'missing required top-level node /{required}')
    if 'product' not in top_names:
        errors.append('missing /product node (AppleImage4 panics without it)')

    chosen = by_path.get('/chosen', {}).get('props', {})
    for required in REQUIRED_CHOSEN:
        if required not in chosen:
            errors.append(f'/chosen is missing {required}')
    if 'random-seed' in chosen and len(chosen['random-seed']) != 64:
        errors.append(f"/chosen/random-seed is {len(chosen['random-seed'])} bytes, expected 64")
    if 'chip-id' in chosen and len(chosen['chip-id']) != 4:
        errors.append('/chosen/chip-id is not 4 bytes')
    if 'unique-chip-id' in chosen and len(chosen['unique-chip-id']) != 8:
        errors.append('/chosen/unique-chip-id is not 8 bytes')
    if 'dram-base' in chosen and len(chosen['dram-base']) != 8:
        errors.append('/chosen/dram-base is not 8 bytes')
    if 'dram-size' in chosen and len(chosen['dram-size']) != 8:
        errors.append('/chosen/dram-size is not 8 bytes')
    if 'owned_memory_size' in expect and 'darwinboot-memory-size' in chosen:
        value = struct.unpack('<Q', chosen['darwinboot-memory-size'])[0]
        if value != expect['owned_memory_size']:
            errors.append(f"/chosen/darwinboot-memory-size is {value:#x}, expected {expect['owned_memory_size']:#x}")

    # CHRP NVRAM proxy: header checksums and the Adler-32 of the common bank.
    if 'nvram-proxy-data' in chosen:
        bank = chosen['nvram-proxy-data']
        if len(bank) != 8192:
            errors.append(f'nvram-proxy-data is {len(bank)} bytes, expected 8192')
        else:
            if struct.unpack_from('<I', bank, 16)[0] != zlib.adler32(bank[20:]):
                errors.append('nvram-proxy-data: Adler-32 of the common data area is wrong')
            for offset, name in ((0, 'nvram'), (32, 'common'), (2096, 'free')):
                header = bank[offset:offset + 16]
                # CHRP header: u8 signature 0x70, u8 checksum, u16 size/16, char name[12]
                if header[4:16].rstrip(b'\0') != name.encode():
                    errors.append(f'nvram-proxy-data: header at {offset} is not {name!r}')
                checksum = sum(header[:1] + header[2:])
                while checksum > 255:
                    checksum = (checksum & 255) + (checksum >> 8)
                if header[1] != checksum:
                    errors.append(f'nvram-proxy-data: {name!r} header checksum is wrong')
        if 'nvram-bank-size' in chosen and struct.unpack('<I', chosen['nvram-bank-size'])[0] != len(bank):
            errors.append('nvram-bank-size does not match the proxy size')

    # Memory-map placeholders must match the inputs the loader will hand over.
    memory_map = by_path.get('/chosen/memory-map', {}).get('props', {})
    for required in expect.get('memory_map', []):
        if required not in memory_map:
            errors.append(f'/chosen/memory-map is missing the {required} placeholder')
        elif len(memory_map[required]) != 16:
            errors.append(f'/chosen/memory-map/{required} is not 16 bytes')

    # CPUs: one node per requested MPIDR, boot CPU first.
    cpu_list = by_path.get('/cpus', {}).get('children', [])
    if len(cpu_list) != len(expect['cpu_regs']):
        errors.append(f'/cpus has {len(cpu_list)} nodes, expected {len(expect["cpu_regs"])}')
    else:
        for index, (cpu, reg) in enumerate(zip(cpu_list, expect['cpu_regs'])):
            value = cpu['props'].get('reg')
            if value is None or struct.unpack('<I', value)[0] != reg:
                errors.append(f'/cpus/cpu{index}/reg does not match {reg:#x}')
            if 'timebase-frequency' not in cpu['props']:
                errors.append(f'/cpus/cpu{index} has no timebase-frequency')
        state = cpu_list[0]['props'].get('state')
        if state != b'running\0':
            errors.append('/cpus/cpu0 state is not "running"')
    has_psci = 'psci' in top_names
    if len(expect['cpu_regs']) > 1 and not has_psci:
        errors.append('multi-CPU tree has no /psci node')
    if len(expect['cpu_regs']) == 1 and has_psci:
        errors.append('single-CPU tree must not declare /psci')

    # GIC child reg must stay inside the arm-io ranges window.
    arm_io = by_path.get('/arm-io')
    if arm_io:
        ranges = arm_io['props'].get('ranges')
        intc = by_path.get('/arm-io/intc', {}).get('props', {})
        if not ranges or len(ranges) != 24:
            errors.append('/arm-io/ranges is not 3 cells')
        elif 'reg' in intc:
            values = struct.unpack('<4Q', intc['reg'])
            window = struct.unpack('<3Q', ranges)[2]
            if values[0] + values[1] > window or values[2] + values[3] > window:
                errors.append('/arm-io/intc/reg lies outside the /arm-io ranges window')
        else:
            errors.append('/arm-io/intc has no reg')
        if intc.get('compatible') != b'arm,gic-v3\0':
            errors.append('/arm-io/intc compatible is not arm,gic-v3')
        uart = by_path.get('/arm-io/uart', {}).get('props', {})
        if not uart:
            errors.append('/arm-io/uart node is missing')
        elif 'reg' in uart and ranges and len(ranges) == 24:
            offset, size = struct.unpack('<2Q', uart['reg'])
            if offset + size > struct.unpack('<3Q', ranges)[2]:
                errors.append('/arm-io/uart/reg lies outside the /arm-io ranges window')

    # --- measured platform addresses ---------------------------------------
    # A tree that claims to carry the measured board values must match the
    # constants (or the CLI overrides the caller supplied); --check compares them so
    # an edited or stale tree cannot pass as measured.
    addresses = expect.get('addresses') or {}
    if addresses:
        def u64(properties, name):
            raw = properties.get(name)
            return None if raw is None else struct.unpack('<Q', raw)[0]

        def check_value(label, got, expected):
            if got != expected:
                errors.append(f'{label} is {got:#x}, expected measured {expected:#x}')

        dram_base = addresses.get('dram_base')
        if dram_base is not None and 'dram-base' in chosen:
            check_value('/chosen/dram-base', u64(chosen, 'dram-base'), dram_base)
        if 'dram_size' in expect and 'dram-size' in chosen:
            check_value('/chosen/dram-size', u64(chosen, 'dram-size'), expect['dram_size'])

        cpus = by_path.get('/cpus', {}).get('children', [])
        timebase = addresses.get('timebase')
        if cpus:
            raw = cpus[0]['props'].get('timebase-frequency')
            if raw is not None and len(raw) == 4 and timebase is not None:
                check_value('/cpus/cpu0/timebase-frequency', struct.unpack('<I', raw)[0], timebase)
            if cpus[0]['props'].get('compatible') is not None:
                if cpus[0]['props']['compatible'] != CPU_COMPATIBLE:
                    errors.append('/cpus/cpu0/compatible is not the measured CPU compatible string')

        arm_io_props = by_path.get('/arm-io', {}).get('props', {})
        ranges_raw = arm_io_props.get('ranges')
        ranges_values = struct.unpack('<3Q', ranges_raw) if ranges_raw and len(ranges_raw) == 24 else None
        armio_base = addresses.get('armio_base')
        armio_size = addresses.get('armio_size')
        if ranges_values is not None and armio_base is not None and armio_size is not None:
            if ranges_values != (0, armio_base, armio_size):
                errors.append(f'/arm-io/ranges is {ranges_values!r}, expected the measured window '
                              f'(0, {armio_base:#x}, {armio_size:#x})')
        if ranges_values is not None:
            intc_reg = by_path.get('/arm-io/intc', {}).get('props', {}).get('reg')
            if intc_reg is not None and len(intc_reg) == 32:
                gic_dist = addresses.get('gic_dist')
                gic_redist = addresses.get('gic_redist')
                gic_dist_size = addresses.get('gic_dist_size')
                gic_redist_size = addresses.get('gic_redist_size')
                if None not in (gic_dist, gic_redist, gic_dist_size, gic_redist_size):
                    expected = (gic_dist - armio_base, gic_dist_size,
                                gic_redist - armio_base, gic_redist_size)
                    got = struct.unpack('<4Q', intc_reg)
                    if got != expected:
                        errors.append(f'/arm-io/intc/reg is {tuple(hex(v) for v in got)}, expected the '
                                      f'measured GIC windows {tuple(hex(v) for v in expected)}')
            uart_reg = by_path.get('/arm-io/uart', {}).get('props', {}).get('reg')
            uart_base = addresses.get('uart_base')
            uart_size = addresses.get('uart_size')
            if uart_reg is not None and len(uart_reg) == 16 and uart_base is not None and uart_size is not None:
                expected = (uart_base - armio_base, uart_size)
                got = struct.unpack('<2Q', uart_reg)
                if got != expected:
                    errors.append(f'/arm-io/uart/reg is {tuple(hex(v) for v in got)}, expected the '
                                  f'measured UART window {tuple(hex(v) for v in expected)}')

    # --- identity check (product) -----------------------------------------
    # iPhone X identity the userland must see.
    product = by_path.get('/product', {}).get('props', {})
    expected_product = {'product-name': b'iPhone X\0',
                        'product-description': b'iPhone X\0',
                        'artwork-device-idiom': b'phone\0',
                        'artwork-display-gamut': b'P3\0',
                        'compatible-device-fallback': b'iPhone9,2\0'}
    for key, value in expected_product.items():
        if product.get(key) != value:
            errors.append(f'/product/{key} is {product.get(key)!r}, expected {value!r}')
    if 'artwork-scale-factor' in product and struct.unpack('<I', product['artwork-scale-factor'])[0] != 3:
        errors.append('/product/artwork-scale-factor is not 3')
    if 'artwork-device-subtype' in product and struct.unpack('<I', product['artwork-device-subtype'])[0] != 2436:
        errors.append('/product/artwork-device-subtype is not 2436')

    buttons = by_path.get('/buttons', {}).get('props', {})
    if 'home-button-type' not in buttons:
        errors.append('/buttons is missing home-button-type')
    elif struct.unpack('<I', buttons['home-button-type'])[0] != 2:
        errors.append('/buttons/home-button-type is not 2 (Home-button-less device expected)')
    names = buttons.get('button-names', b'')
    if b'voldown\0' not in names or b'volup\0' not in names or b'hold\0' not in names:
        errors.append('/buttons/button-names lacks hold/voldown/volup')
    return errors


