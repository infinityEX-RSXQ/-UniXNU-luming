def parse_int_base0(value: str) -> int:
    return int(value, 0)


def parse_int_hex(value: str) -> int:
    return int(value, 16)


def parse_cpu_regs(value: str) -> list[int]:
    try:
        return [int(item, 0) for item in value.split(',')]
    except ValueError:
        raise argparse.ArgumentTypeError('--cpu-regs must be comma-separated integers') from None


def describe_address(value) -> str:
    """Human form of a platform constant for --help; 'unmeasured' if a value is None."""
    return f'{value:#x}' if isinstance(value, int) else 'unmeasured'


def resolve_addresses(args, parser) -> dict:
    """Measured constants, CLI overrides, or the synthetic structural placeholder set."""
    addresses = {
        'dram_base': DRAM_BASE,
        'armio_base': ARMIO_BASE,
        'armio_size': ARMIO_SIZE,
        'gic_dist': GIC_DIST,
        'gic_dist_size': GIC_DIST_SIZE,
        'gic_redist': GIC_REDIST,
        'gic_redist_size': GIC_REDIST_SIZE,
        'uart_base': UART_BASE,
        'uart_size': UART_SIZE,
        'timebase': TIMEBASE,
    }
    overrides = []
    for name in addresses:
        flag = getattr(args, name, None)
        if flag is not None:
            addresses[name] = flag
            overrides.append(name)
    missing = [name for name in addresses if addresses[name] is None]
    if missing and not args.todo_placeholder_addresses:
        parser.error(
            'TODO(device): no measured value for ' + ', '.join(missing) + '.\n'
            'All luming platform addresses are measured constants in this file (live DTB/iomem,\n'
            '2026-10-22); a value is only None if a revision lost its measurement.  Restore it from\n'
            'the evidence listed at the top of this file, or pass the matching flag for a one-off\n'
            'tree.  For a structural-only ADT encoding test pass --todo-placeholder-addresses\n'
            '(never bootable).')
    if missing:
        for name in missing:
            addresses[name] = PLACEHOLDER_ADDRESSES[name]
        print('WARNING: --todo-placeholder-addresses: the platform addresses below are SYNTHETIC\n'
              '         structural placeholders, not luming values. This tree is NOT bootable.',
              file=sys.stderr)
        for name in missing:
            print(f'         {name} = {addresses[name]:#x} (placeholder)', file=sys.stderr)
        addresses['_placeholder'] = True
    elif args.todo_placeholder_addresses:
        print('NOTE: --todo-placeholder-addresses: every platform address is measured '
              '(2026-10-22); flag has no effect.', file=sys.stderr)
    if overrides:
        addresses['_overrides'] = tuple(overrides)
    return addresses


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description='Generate the Apple device tree for Xiaomi Civi 5 Pro (luming)', allow_abbrev=False)
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'build/luming/boot/kernel.macho.adt')
    parser.add_argument('--dram-size', type=parse_int_base0, default=None,
                        help='physical DRAM size in bytes (measured 12 GiB SKU: 0x300000000; '
                             'the payload step passes board.toml [payload] dram_size)')
    parser.add_argument('--owned-memory-size', type=parse_int_base0, default=None,
                        help='DarwinBoot contiguous window, 256 MiB..8 GiB in 2 MiB steps (TODO(device): '
                             'known only from the UEFI memory map after kernel entry)')
    parser.add_argument('--root-match-volume-uuid', default=None,
                        help='/chosen/root-matching: select the root IOMedia by UUID (TODO(device): '
                             'offline APFS extraction of the target image)')
    parser.add_argument('--unique-chip-id', type=parse_int_hex, default=None,
                        help='/chosen/unique-chip-id (8 bytes); software identity seed, never stored in the repo')
    parser.add_argument('--chip-id', type=parse_int_hex, default=None,
                        help='/chosen/chip-id (4 bytes); default 0x8015 = A11 CPID of the iPhone X userland')
    parser.add_argument('--cpu-regs', type=parse_cpu_regs,
                        default=[0, 0x100, 0x200, 0x300, 0x400, 0x500, 0x600, 0x700],
                        help='comma-separated MPIDR Affinity1 values; the boot CPU (0) first. '
                             'Measured on the live luming DT: 8 cores at 0,0x100..0x700')
    parser.add_argument('--psci-method', choices=['smc', 'hvc'], default='smc',
                        help='/psci method used for the secondary-CPU start; the live DT cpus node uses '
                             'enable-method "psci" (measured); smc is the Qualcomm PSCI conduit convention')
    # Platform addresses: measured module constants (live DTB/iomem, 2026-10-22).  The
    # flags exist so a one-off tree can be produced from other measured values; they
    # mark the tree as an unverified override unless --soc-verified is also given.
    parser.add_argument('--dram-base', type=parse_int_base0, default=None,
                        help=f'override the measured DRAM base ({describe_address(DRAM_BASE)})')
    parser.add_argument('--armio-base', type=parse_int_base0, default=None,
                        help=f'override the derived arm-io window base ({describe_address(ARMIO_BASE)})')
    parser.add_argument('--armio-size', type=parse_int_base0, default=None,
                        help=f'override the derived arm-io window size ({describe_address(ARMIO_SIZE)})')
    parser.add_argument('--gic-dist', type=parse_int_base0, default=None,
                        help=f'override the measured GIC distributor base ({describe_address(GIC_DIST)})')
    parser.add_argument('--gic-redist', type=parse_int_base0, default=None,
                        help=f'override the measured GIC redistributor base ({describe_address(GIC_REDIST)})')
    parser.add_argument('--gic-redist-size', type=parse_int_base0, default=None,
                        help=f'override the measured GIC redistributor size ({describe_address(GIC_REDIST_SIZE)})')
    parser.add_argument('--uart-base', type=parse_int_base0, default=None,
                        help=f'override the measured debug UART base ({describe_address(UART_BASE)})')
    parser.add_argument('--timebase-frequency', type=parse_int_base0, default=None,
                        help=f'override the measured architectural counter frequency ({describe_address(TIMEBASE)})')
    parser.add_argument('--todo-placeholder-addresses', action='store_true',
                        help='structural-only ADT validation: fill any unmeasured (None) platform address '
                             'with SYNTHETIC placeholders (never bootable).  Unnecessary while every '
                             'constant is measured; the tool then refuses a tree only for a None value')
    parser.add_argument('--soc-verified', action='store_true',
                        help='assert that one-off CLI platform-address overrides were measured on the '
                             'board; suppresses the --check override warning (measured constants are the '
                             'default and need no flag)')
    parser.add_argument('--packed-data-ramdisk', action='store_true',
                        help='reserve the PackedRAMDisk memory-map placeholder')
    parser.add_argument('--data-ramdisk', action='store_true',
                        help='reserve the dense RAMDisk memory-map placeholder')
    parser.add_argument('--trust-cache', action='store_true',
                        help='reserve the TrustCache memory-map placeholder')
    parser.add_argument('--ipad-identity', '--iphone-identity', dest='ipad_identity',
                        action='store_true', default=False,
                        help='compatibility flag of the base payload step. The iPhone identity is always '
                             'written; the flag adds the four activation/security-status properties '
                             '(documented delta from UniXNU-sheng: there it selects the iPad product '
                             'identity, here identity is always iPhone10,3, see docs/guide/mobilegestalt.md)')
    parser.add_argument('--apple-buttons', action='store_true',
                        help="write Apple's full button-names list including the ringer switch "
                             '(the Civi 5 Pro has no ringer switch, so the default omits it)')
    parser.add_argument('--check', action='store_true',
                        help='validate the existing --output file instead of writing a new tree')
    args = parser.parse_args(argv)

    if args.check:
        if not args.output.is_file():
            parser.error(f'--check: {args.output} does not exist; generate the tree first')
        data = args.output.read_bytes()
        memory_map = []
        if args.data_ramdisk:
            memory_map.append('RAMDisk')
        if args.packed_data_ramdisk:
            memory_map.append('PackedRAMDisk')
        if args.trust_cache:
            memory_map.append('TrustCache')
        addresses = resolve_addresses(args, parser)
        expect = {'cpu_regs': args.cpu_regs, 'memory_map': memory_map, 'addresses': addresses}
        if args.dram_size is not None:
            expect['dram_size'] = args.dram_size
        if args.owned_memory_size is not None:
            expect['owned_memory_size'] = args.owned_memory_size
        errors = check_tree(data, expect)
        if addresses.get('_placeholder'):
            print('WARNING: this tree carries SYNTHETIC --todo-placeholder-addresses; it is NOT '
                  'bootable and does not carry the measured constants.', file=sys.stderr)
        overrides = addresses.get('_overrides')
        if overrides and not args.soc_verified:
            print('WARNING: platform addresses include CLI overrides ('
                  + ', '.join(overrides) + '); they are not the measured constants. '
                  'Pass --soc-verified only if they were measured on the board.', file=sys.stderr)
        if errors:
            print(f'luming ADT check: FAIL ({len(errors)} error(s))', file=sys.stderr)
            for error in errors:
                print(f'  - {error}', file=sys.stderr)
            return 1
        if addresses.get('_placeholder'):
            status = 'synthetic placeholders (NOT BOOTABLE)'
        elif overrides:
            status = 'CLI overrides' + (' (asserted verified)' if args.soc_verified else ' (unverified)')
        else:
            status = 'measured on the luming board 2026-10-22'
        print(f'luming ADT check: PASS ({len(data)} bytes, addresses {status})')
        return 0

    if args.dram_size is None:
        parser.error('--dram-size is required (the payload step passes it from board.toml [payload] dram_size)')
    addresses = resolve_addresses(args, parser)
    if args.chip_id is None:
        args.chip_id = CHIP_ID_DEFAULT
    if args.unique_chip_id is None:
        # The base payload step only supplies the seed when --unique-chip-id is
        # given; board.toml declares unique_chip_id = "required", so warn loudly.
        print('WARNING: no --unique-chip-id; /chosen unique-chip-id is omitted '
              '(board.toml declares it required)', file=sys.stderr)
    try:
        tree = build_tree(args.dram_size, addresses,
                          owned_memory_size=args.owned_memory_size,
                          root_match_volume_uuid=args.root_match_volume_uuid,
                          chip_id=args.chip_id if args.unique_chip_id is not None else None,
                          unique_chip_id=args.unique_chip_id,
                          cpu_regs=args.cpu_regs, psci_method=args.psci_method,
                          packed_data_ramdisk=args.packed_data_ramdisk,
                          data_ramdisk=args.data_ramdisk, trust_cache=args.trust_cache,
                          ipad_identity=args.ipad_identity, apple_buttons=args.apple_buttons)
    except ValueError as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(tree)
    print(f'luming ADT: {args.output} ({len(tree)} bytes, {len(args.cpu_regs)} CPU(s), '
          f'dram {args.dram_size:#x})')
    if addresses.get('_placeholder'):
        status = 'SYNTHETIC PLACEHOLDERS - NOT BOOTABLE'
    elif addresses.get('_overrides'):
        status = ('CLI OVERRIDES (unverified; pass --soc-verified only after measuring them on the board: '
                  + ', '.join(addresses['_overrides']) + ')')
    else:
        status = 'MEASURED on the luming board 2026-10-22 (live DTB/iomem)'
    print(f'platform addresses: {status}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
