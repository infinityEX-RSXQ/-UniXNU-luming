#!/usr/bin/env python3
"""Generate the Apple-flat-device-tree (ADT) for the Xiaomi Civi 5 Pro (luming).

The target userland is iOS 16.7.16 (iPhone10,3 / D22AP, Darwin 22.6.0,
xnu-8796.132-era kernelcache), so the platform identity written here is the
iPhone X identity documented in UniXNU docs/guide/mobilegestalt.md and decoded
from Apple's own DeviceTree.d22ap.im4p (see scripts/luming_identity.py).

The node encoding mirrors scripts/make-sheng-adt.py (UniXNU-sheng), which is
the proven Apple ADT encoder for this kernel family:

    node := u32 property_count, u32 child_count,
            { char name[32]; u32 length; u8 value[length]; pad to 4 } *,
            node * child_count

Contract with `unixnu build payload` (scripts/unixnu/payload.py): the tool is
called with --output, --dram-size and the optional generic flags below.  The
process must be able to run on a plain macOS or Windows Python 3.11+ with no
third-party packages.

The SoC/board constants at the top were measured on a luming board on 2026-10-22
from its live Android device tree, /proc/iomem and dmesg (evidence paths are in the
constants block below and PORTING.md section 3).  Values that only a boot of this
port can provide (the DarwinBoot owned window, the root-volume UUID, the platform
seed) are not constants of this tool: the payload step passes them as options and
they stay TODO(device) in board.toml.  `--check` verifies the measured platform
addresses carried by a tree and reports them as measured; if a constant is set back
to None, generation refuses instead of fabricating a value (structural encoding
tests only may pass --todo-placeholder-addresses, and such a tree is not bootable).

Usage:
    # generate (as the payload step does)
    python scripts/make-luming-adt.py --output kernel.macho.adt \
        --dram-size 0x300000000 --owned-memory-size 0x40000000 \
        --chip-id 8015 --unique-chip-id 0123456789abcdef \
        --cpu-regs 0,0x100,0x200,0x300,0x400,0x500,0x600,0x700 \
        --packed-data-ramdisk --ipad-identity

    # validate an existing tree (binary structure contract + required nodes)
    python scripts/make-luming-adt.py --output kernel.macho.adt --check
"""
