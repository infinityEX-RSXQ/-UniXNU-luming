def build_tree(dram_size: int, addresses: dict, owned_memory_size=None,
               root_match_volume_uuid=None, chip_id=None, unique_chip_id=None,
               cpu_regs=(0,), psci_method='smc', packed_data_ramdisk=False,
               data_ramdisk=False, trust_cache=False, ipad_identity=False,
               apple_buttons=False) -> bytes:
    """Return the serialised Apple device tree.

    `addresses` must supply every platform address: the measured constants (or CLI
    overrides for a one-off tree), or the synthetic --todo-placeholder-addresses set
    for a structural encoding test.  The tool never invents a platform address.
    """
    missing = [name for name in addresses if addresses[name] is None]
    if missing:
        raise ValueError('missing platform addresses (TODO(device)): ' + ', '.join(missing))
    dram_base = addresses['dram_base']
    armio_base = addresses['armio_base']
    armio_size = addresses['armio_size']
    gic_dist = addresses['gic_dist']
    gic_redist = addresses['gic_redist']
    gic_redist_size = addresses['gic_redist_size']
    uart_base = addresses['uart_base']
    timebase = addresses['timebase']
    for name in ('gic_dist', 'gic_redist', 'uart_base'):
        if addresses[name] < armio_base:
            raise ValueError(f'{name} ({addresses[name]:#x}) lies below the arm-io window '
                             f'base {armio_base:#x}; the ADT can only express child offsets inside the window')
        if addresses[name] - armio_base >= armio_size:
            raise ValueError(f'{name} ({addresses[name]:#x}) lies outside the arm-io window '
                             f'({armio_base:#x} + {armio_size:#x})')
    if packed_data_ramdisk and data_ramdisk:
        raise ValueError('--data-ramdisk and --packed-data-ramdisk are exclusive')
    if (unique_chip_id is None) != (chip_id is None):
        raise ValueError('--unique-chip-id and --chip-id must be supplied together')
    if unique_chip_id is not None and not (0 < unique_chip_id < 1 << 64 and 0 < chip_id < 1 << 32):
        raise ValueError('--unique-chip-id must fit 8 bytes and --chip-id 4 bytes, both nonzero')
    if not cpu_regs:
        raise ValueError('at least one CPU is required')
    if cpu_regs[0] != 0 or len(set(cpu_regs)) != len(cpu_regs) or len(cpu_regs) > 8:
        raise ValueError('--cpu-regs: up to eight distinct Affinity1-numbered cores, boot CPU 0 first')
    if any(reg < 0 or reg > 0xffff or reg & 0xff for reg in cpu_regs):
        raise ValueError('--cpu-regs values are Affinity1 MPIDRs (0x000, 0x100, ...)')
    if owned_memory_size is not None and (
            not 0x10000000 <= owned_memory_size <= 0x200000000 or owned_memory_size % 0x200000):
        raise ValueError('Owned memory must be 256 MiB to 8 GiB, aligned to 2 MiB')

    chosen_props = [
        ('random-seed', os.urandom(64)),
        # Without these XNU never publishes IOPlatformUUID and gethostuuid()
        # blocks forever for callers (configd) that pass a zero timeout.
        *([('unique-chip-id', struct.pack('<Q', unique_chip_id)),
           ('chip-id', struct.pack('<I', chip_id)),
           # d22ap board id from the verified BuildManifest (ApBoardID 0x06).
           ('board-id', struct.pack('<I', 0x06))] if unique_chip_id is not None else []),
        ('osenvironment', b'main\0'),
        # Security status of a dev-fused, undemoted board; MobileGestalt and
        # mobileactivationd read these (Hactivation path, no SEP/baseband).
        # Only written for the iOS/phone identity (--ipad-identity compatibility
        # flag keeps the same 4 properties the sheng tool emits).
        *([('certificate-production-status', struct.pack('<I', SECURITY_STATUS[0])),
           ('effective-production-status-ap', struct.pack('<I', SECURITY_STATUS[1])),
           ('certificate-security-mode', struct.pack('<I', SECURITY_STATUS[2])),
           ('effective-security-mode-sep', struct.pack('<I', SECURITY_STATUS[3]))]
          if ipad_identity else []),
        # The Data volume is volatile for this port until the UFS root path
        # works; a persistent seed must not set this (datamigrator skips).
        *([('ephemeral-storage', struct.pack('<I', 1))]
          if (packed_data_ramdisk or data_ramdisk) else []),
        *([('darwinboot-memory-size', struct.pack('<Q', owned_memory_size))]
          if owned_memory_size else []),
        # MEASURED (live DTB + iomem): DRAM_BASE.  --dram-size is the physical size
        # from board.toml [payload] (the 12 GiB SKU of the measured unit).
        ('dram-base', struct.pack('<Q', dram_base)),
        ('dram-size', struct.pack('<Q', dram_size)),
        # Image4 hash algorithm; the iPhone X tree specifies sha2-384.
        ('crypto-hash-method', b'sha2-384\0'),
        # iPhone X panel scale (userland identity), not a luming panel measurement.
        ('display-scale', struct.pack('<I', DISPLAY_SCALE)),
        *([('root-matching', root_matching(root_match_volume_uuid))]
          if root_match_volume_uuid else []),
        # Keep AMFI enforcing its platform-code policy; this does not relax it.
        ('amfi-only-platform-code', struct.pack('<I', 1)),
        *empty_nvram_proxy(),
    ]
    memory_map = []
    if data_ramdisk:
        memory_map.append(('RAMDisk', bytes(16)))
    if packed_data_ramdisk:
        memory_map.append(('PackedRAMDisk', bytes(16)))
    if trust_cache:
        memory_map.append(('TrustCache', bytes(16)))
    chosen_children = [node('memory-map', memory_map),
                       # Read by the original AppleImage4 at start-up.
                       node('manifest-properties')]

    product_props = list(luming_identity.PRODUCT_PROPS)

    buttons = [
        ('compatible', b'buttons\0'),
        ('device_type', b'buttons\0'),
        ('button-names', BUTTON_NAMES_APPLE if apple_buttons else BUTTON_NAMES_NO_RINGER),
        # 2 = no mechanical Home button; the lock screen uses swipe-up gestures.
        ('home-button-type', struct.pack('<I', 2)),
    ]

    tree = node('device-tree', [
        # hw.product/hw.machine/hw.target come from the root model/target-type
        # (ArmDTPlatform).  Root `compatible` stays the board's own strings:
        # an Apple board name can match original platform kexts (docs/guide/
        # mobilegestalt.md), and the identity is carried by model/target-type.
        ('compatible', BOARD_COMPATIBLE),
        ('#address-cells', struct.pack('<I', 2)),
        ('#size-cells', struct.pack('<I', 2)),
        *luming_identity.ROOT_IDENTITY,
    ], [
        node('chosen', chosen_props, chosen_children),
        node('cpus', children=cpu_nodes(list(cpu_regs), timebase)),
        *([node('psci', [('compatible', b'arm,psci-1.0\0'),
                         ('method', psci_method.encode() + b'\0')])] if len(cpu_regs) > 1 else []),
        node('defaults', [
            # Suspend/resume is not implemented for this board.
            ('sleep-disabled', struct.pack('<I', 1)),
            # No SEP/keybag path on a Qualcomm board; keybagd then reads the
            # system keybag as a plain plist instead of an effaceable key.
            # Evidence: refs/UniXNU-guacamole/scripts/mkadt.py (same decision).
            ('no-effaceable-storage', struct.pack('<I', 1)),
        ]),
        node('options', []),
        node('product', product_props),
        node('buttons', buttons),
        node('arm-io', [
            ('device_type', b'arm-io\0'),
            ('#address-cells', struct.pack('<I', 2)),
            ('#size-cells', struct.pack('<I', 2)),
            ('ranges', struct.pack('<QQQ', 0, armio_base, armio_size)),
        ], [
            node('intc', [
                ('compatible', b'arm,gic-v3\0'),
                ('reg', struct.pack('<4Q',
                                    gic_dist - armio_base, GIC_DIST_SIZE,
                                    gic_redist - armio_base, gic_redist_size)),
                ('redistributor-stride', struct.pack('<Q', GIC_REDIST_STRIDE)),
            ]),
            # MEASURED (live DT + iomem): UART 0xA9C000/0x4000, interrupt 579 (0x243),
            # chosen stdout-path serial0:115200n8.  The node lets the platform
            # expert/driver match a console.
            node('uart', [
                ('compatible', b'qcom,geni-uart\0'),
                ('device_type', b'serial\0'),
                ('reg', struct.pack('<QQ', uart_base - armio_base, UART_SIZE)),
            ]),
            # UFS host: class-match node only.  NativeUfs takes its physical
            # windows from the measured board constants (UFS_HC/UFS_HC_SIZE); the
            # live DT reg also has the ICE/MCQ windows, which the driver port decides.
            node('ufshc', [('compatible', b'qcom,sm8735-ufshc\0')]),
        ]),
    ])
    return tree


